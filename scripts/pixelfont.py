def glyph_rects(ch, u, ox=0, oy=0):
    out = []
    for y, row in enumerate(F[ch]):
        x = 0
        while x < 5:
            if row[x] == '#':
                x2 = x
                while x2 < 5 and row[x2] == '#':
                    x2 += 1
                out.append(f'<rect x="{ox+x*u}" y="{oy+y*u}" width="{(x2-x)*u}" height="{u}"/>')
                x = x2
            else:
                x += 1
    return ''.join(out)


def pixel_text(text, u, cx, y, fill, shadow=None, wave=False, base_delay=0.0, soff=None):
    width = len(text) * 6 * u - u
    x0 = cx - width / 2
    so = u if soff is None else soff
    parts = []
    for i, ch in enumerate(text.upper()):
        if ch == ' ' or ch not in F:
            continue
        gx = x0 + i * 6 * u
        body = f'<g fill="{fill}">{glyph_rects(ch, u)}</g>'
        if shadow:
            body = f'<g fill="{shadow}">{glyph_rects(ch, u, so, so)}</g>' + body
        cls = ' class="lt"' if wave else ''
        st = f' style="animation-delay:{base_delay + i*0.11:.2f}s"' if wave else ''
        parts.append(f'<g transform="translate({gx:.1f},{y})"><g{cls}{st}>{body}</g></g>')
    return ''.join(parts)


def views_group(text, cx=490, y=44, u=8):
    """Eye icon + big pixel number, centred on cx."""
    eu = 5
    eye_w, eye_h = 11 * eu, 7 * eu
    gap = 26
    num_w = len(text) * 6 * u - u
    total = eye_w + gap + num_w
    x0 = cx - total / 2
    ey = y + (7 * u - eye_h) / 2
    eye = ''
    for r, row in enumerate(EYE):
        for c, ch in enumerate(row):
            if ch == '#':
                eye += f'<rect x="{x0 + c*eu:.1f}" y="{ey + r*eu:.1f}" width="{eu}" height="{eu}"/>'
    # pupil terpisah supaya bisa "berkedip"
    eye_g = (f'<g class="eye" style="transform-origin:{x0 + eye_w/2:.1f}px {ey + eye_h/2:.1f}px" fill="#f97316">{eye}</g>')
    num = pixel_text(text, u, x0 + eye_w + gap + num_w / 2, y, '#fafafa', shadow='#c2410c', wave=True, soff=4)
    return eye_g + num
